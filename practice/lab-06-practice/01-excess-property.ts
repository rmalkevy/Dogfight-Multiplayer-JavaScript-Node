// Спитай студентів ПЕРЕД перевіркою: який із двох рядків не скомпілюється?
//
// Очікування від tsc: ОДНА помилка, TS2353 на рядку з s (літерал із зайвим y).
// Рядок з q компілюється: зайве y через змінну дозволене (структурна типізація).
const p = { x: 1, y: 2 };
const q: { x: number } = p; // ок: зайве y дозволене через змінну
// const r: { x: number; z: number } = p // помилка: немає z (розкоментуй: TS2741)

const s: { x: number } = { x: 1, y: 2 }; // помилка: excess property на літералі

// Типи стерто, у runtime y на місці в обох. Очікування: { x: 1, y: 2 } двічі.
console.log('q', q);
console.log('s', s);
