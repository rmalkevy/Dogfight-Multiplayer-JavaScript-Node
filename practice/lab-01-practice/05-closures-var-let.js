// Експеримент 5 (§5): замикання тримає змінну, а не копію значення.
// Запуск: node 05-closures-var-let.js
//
// Спитай студентів ПЕРЕД запуском, що надрукує кожен цикл.
//
// Очікування: тричі "var 3", потім "let 0", "let 1", "let 2".
// var: одна змінна i на весь цикл, колбеки бачать її фінальне значення.
// let: нова змінна j на кожну ітерацію.
for (var i = 0; i < 3; i++) setTimeout(() => console.log('var', i));
for (let j = 0; j < 3; j++) setTimeout(() => console.log('let', j));
