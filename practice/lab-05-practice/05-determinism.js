// Експеримент 5 (§5): детермінізм симуляції.
// Запуск: node 05-determinism.js        (запусти двічі і порівняй хеші між запусками)
//
// 1000 кроків integrate з однаковим input. Хеш рахується по всіх бітах стану.
// Ту саму симуляцію (sim.js) у Chrome запускає browser.html: хеш A має збігтися.
import './sim.js';

const { run, mulberry32 } = globalThis.sim;
const show = (label, r) => console.log(`${label.padEnd(18)} x ${r.x}  y ${r.y}  hash ${r.hash}`);

// Частина A: чиста функція, без випадковості.
// Очікування: два прогони дають той самий хеш, і між запусками скрипта теж.
console.log('--- A: без випадковості');
show('прогін 1', run());
show('прогін 2', run());

// Частина B: Math.random() у симуляції, навіть крихітний (1e-6).
// Очікування: хеші різні між прогонами; x відрізняється лише в шостому знаку, y однаковий.
// Сервер і клієнт уже роз'їхались, хоча на екрані цього не видно.
console.log('--- B: Math.random()');
show('прогін 1', run(1000, Math.random));
show('прогін 2', run(1000, Math.random));

// Частина C: випадковість з seed. Той самий seed -> той самий хеш, інший seed -> інший.
// Очікування: seed 42 двічі однаковий (і між запусками), seed 43 інший.
console.log('--- C: mulberry32(seed)');
show('seed 42, прогін 1', run(1000, mulberry32(42)));
show('seed 42, прогін 2', run(1000, mulberry32(42)));
show('seed 43', run(1000, mulberry32(43)));
